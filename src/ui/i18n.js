/** Funny deaths line for the results screen. */
export function deathsLine(n, lang) {
  if (lang === 'en') {
    if (n === 0) return 'Lumen died 0 times (suspicious)';
    if (n === 1) return 'Lumen died once (oops)';
    if (n < 5) return `Lumen died ${n} times (it happens)`;
    if (n < 15) return `Lumen died ${n} times (well done)`;
    return `Lumen died ${n} times (record? ask your therapist)`;
  }
  if (n === 0) return 'Lumen est mort 0 fois (louche)';
  if (n === 1) return 'Lumen est mort 1 fois (oups)';
  if (n < 5) return `Lumen est mort ${n} fois (ça arrive)`;
  if (n < 15) return `Lumen est mort ${n} fois (bravo)`;
  return `Lumen est mort ${n} fois (record ? demande à ton psy)`;
}

